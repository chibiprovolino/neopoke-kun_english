def rows(c): return [[ch=='#' for ch in r] for r in G[c].split('|')]
def pair_tile(a,b):
    """2bpp NGP tile (16 bytes) with glyph a in px 0-3 and b in px 4-7. Ink = colour 3."""
    ra,rb=rows(a),rows(b); out=bytearray()
    for y in range(8):
        px=ra[y]+[False]+rb[y]+[False]; w=0
        for x in range(8):
            if px[x]: w|=3<<(14-2*x)
        out+=bytes([w&0xff,w>>8])
    return bytes(out)
